#!/usr/bin/env python3
"""Deterministic Auditor & Data-Chaining Engine (Zero LLM Involvement).

Enforces the single verifiable data lineage:
  runs/<run_id>/manifest.json + metrics.json
    -> results/results.json (verified aggregate + 95% CIs)
    -> paper/generated/numbers.tex (LaTeX macros)
    -> reports/audit_report.md (blocking gate report)
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import math
import random
from pathlib import Path
from typing import Any, Dict, List, Tuple


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def bootstrap_ci(values: List[float], n_boot: int = 2000, alpha: float = 0.05, seed: int = 42) -> Tuple[float, float, float]:
    if not values:
        return 0.0, 0.0, 0.0
    mean = sum(values) / len(values)
    if len(values) == 1:
        return mean, mean, mean
    rng = random.Random(seed)
    n = len(values)
    boots = sorted(sum(values[rng.randrange(n)] for _ in range(n)) / n for _ in range(n_boot))
    lo = boots[int((alpha / 2.0) * n_boot)]
    hi = boots[min(n_boot - 1, int((1.0 - alpha / 2.0) * n_boot))]
    return mean, lo, hi


def cliffs_delta(xs: List[float], ys: List[float]) -> float:
    if not xs or not ys:
        return 0.0
    gt = 0
    lt = 0
    for x in xs:
        for y in ys:
            if x > y:
                gt += 1
            elif x < y:
                lt += 1
    return (gt - lt) / (len(xs) * len(ys))


def audit_runs(runs_dir: Path, harness_files: Optional[List[Path]] = None) -> Dict[str, Any]:
    required_fields = {
        "run_id",
        "experiment",
        "timestamp_utc",
        "git_commit",
        "harness_sha256",
        "dataset_sha256",
        "command",
        "seeds",
        "metrics_file",
        "metrics_sha256",
    }
    errors: List[str] = []
    warnings: List[str] = []
    verified_runs: List[Dict[str, Any]] = []

    if not runs_dir.exists():
        return {"passed": False, "errors": [f"runs directory missing: {runs_dir}"], "warnings": [], "runs": []}

    current_harness_hashes: Dict[str, str] = {}
    if harness_files:
        for hf in harness_files:
            if hf.exists():
                current_harness_hashes[hf.name] = sha256_file(hf)

    for run_path in sorted(p for p in runs_dir.iterdir() if p.is_dir()):
        manifest_path = run_path / "manifest.json"
        if not manifest_path.exists():
            errors.append(f"[{run_path.name}] Missing manifest.json (unsealed run rejected)")
            continue
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except Exception as exc:
            errors.append(f"[{run_path.name}] Invalid JSON in manifest.json: {exc}")
            continue
        missing = sorted(required_fields - set(manifest.keys()))
        if missing:
            errors.append(f"[{run_path.name}] manifest.json missing fields: {missing}")
            continue
        metrics_path = run_path / manifest["metrics_file"]
        if not metrics_path.exists():
            errors.append(f"[{run_path.name}] Metrics file missing: {metrics_path}")
            continue
        actual_sha = sha256_file(metrics_path)
        if actual_sha != manifest["metrics_sha256"]:
            errors.append(
                f"[{run_path.name}] Tamper/checksum mismatch on {manifest['metrics_file']}: "
                f"expected {manifest['metrics_sha256'][:12]}, got {actual_sha[:12]}"
            )
            continue
        metrics_data = json.loads(metrics_path.read_text(encoding="utf-8"))
        verified_runs.append({
            "run_id": manifest["run_id"],
            "experiment": manifest["experiment"],
            "manifest": manifest,
            "metrics": metrics_data,
        })

    if not verified_runs:
        errors.append("No valid sealed runs found under runs/")

    return {
        "audited_at_utc": dt.datetime.now(dt.timezone.utc).isoformat(),
        "passed": len(errors) == 0,
        "verified_run_count": len(verified_runs),
        "errors": errors,
        "warnings": warnings,
        "runs": verified_runs,
    }


def write_numbers_tex(macros: Dict[str, Tuple[str, str]], out_path: Path) -> None:
    """Write deterministic LaTeX macros with provenance comments.

    macros: {MacroName: (formatted_value, provenance_note)}
    """
    lines = [
        "% AUTO-GENERATED BY Research Paper Factory Auditor (DO NOT EDIT BY HAND)",
        "% Every macro traces deterministically to a sealed run_id in runs/<run_id>/manifest.json",
        "",
    ]
    for name, (val, prov) in sorted(macros.items()):
        lines.append(f"\\newcommand{{\\{name}}}{{{val}}} % {prov}")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def check_manuscript_numbers(tex_files: List[Path], numbers_tex: Path) -> Dict[str, Any]:
    """Audit LaTeX sources for defined/used macros and suspicious raw percentages."""
    defined = set()
    if numbers_tex.exists():
        import re
        for m in re.finditer(r"\\newcommand\{\\([A-Za-z]+)\}", numbers_tex.read_text(encoding="utf-8")):
            defined.add(m.group(1))
    used = set()
    raw_percent_warnings: List[str] = []
    import re
    for tf in tex_files:
        if not tf.exists():
            continue
        for lineno, line in enumerate(tf.read_text(encoding="utf-8").splitlines(), 1):
            if line.strip().startswith("%"):
                continue
            for m in re.finditer(r"\\([A-Za-z]{4,})\b", line):
                tok = m.group(1)
                if tok in defined:
                    used.add(tok)
            # Flag raw numeric percentages outside macro definitions / table specs
            if re.search(r"\b\d+\.\d+\\%", line):
                raw_percent_warnings.append(f"{tf.name}:{lineno}: {line.strip()[:100]}")
    return {
        "defined_macros": len(defined),
        "used_macros": len(used),
        "raw_percent_warnings": raw_percent_warnings,
    }
